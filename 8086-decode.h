// A field with bit_cnt == 0 reads no bits; it is implied by the encoding and
// just sets the field to `value` (e.g. {F_REG, 0, 0} = accumulator).
// Operand order: d == 1 puts the reg side (REG/SR) first, d == 0 (the default)
// puts the other side (RM/ADDR/DX/data) first.
enum FieldType : u8 {
    F_END, // zero-filled slots terminate fields[]
    F_LITERAL,
    F_D,
    F_W,
    F_S,
    F_V,
    F_Z,
    F_MOD,
    F_REG,
    F_RM,
    F_SR,
    F_DISP_LO,
    F_DISP_HI,
    F_DATA,
    F_DATA_IF_W,
    F_DATA_IF_SW,
    F_DATA_LO,
    F_DATA_HI,
    F_ADDR_LO,
    F_ADDR_HI,
    F_IP_INC_LO,
    F_IP_INC_HI,
    F_IP_INC8,
    F_IP_LO,
    F_IP_HI,
    F_CS_LO,
    F_CS_HI,
    F_XXX,
    F_YYY,
    F_DX,  // implicit DX port operand (IN/OUT variable port)
    F_FAR, // implicit intersegment (far) call/jmp/ret
};

struct BitField {
    FieldType type;
    u8 bit_cnt;
    u8 value = 0;
};

struct Encoding {
    OpType op;
    BitField fields[10];
};

